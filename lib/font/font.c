const size_t font_glyph_count = sizeof(font_glyphs) / sizeof(font_glyphs[0]);

Font font_default(void) {
  return (Font){
      .glyphs = font_glyphs,
      .count = font_glyph_count,
      .height = 5,
      .line_height = 7,
  };
}

const FontGlyph *font_get_glyph(Font font, uint32_t codepoint) {
  size_t low = 0;
  size_t high = font.count;

  while (low < high) {
    size_t mid = low + (high - low) / 2;
    uint32_t value = font.glyphs[mid].codepoint;

    if (value == codepoint)
      return &font.glyphs[mid];

    if (value < codepoint)
      low = mid + 1;
    else
      high = mid;
  }

  if (codepoint != '?')
    return font_get_glyph(font, '?');

  return NULL;
}

uint32_t font_decode_next(const char **text) {
  const uint8_t *s = (const uint8_t *)*text;
  uint32_t cp;

  if (!s[0])
    return 0;

  if (s[0] < 0x80) {
    *text += 1;
    return s[0];
  }

  if ((s[0] & 0xE0) == 0xC0 && s[1] && (s[1] & 0xC0) == 0x80) {
    cp = ((uint32_t)(s[0] & 0x1F) << 6) | (uint32_t)(s[1] & 0x3F);
    *text += 2;
    return cp >= 0x80 ? cp : '?';
  }

  if ((s[0] & 0xF0) == 0xE0 && s[1] && s[2] && (s[1] & 0xC0) == 0x80 &&
      (s[2] & 0xC0) == 0x80) {
    cp = ((uint32_t)(s[0] & 0x0F) << 12) | ((uint32_t)(s[1] & 0x3F) << 6) |
         (uint32_t)(s[2] & 0x3F);
    *text += 3;
    return cp >= 0x800 && !(cp >= 0xD800 && cp <= 0xDFFF) ? cp : '?';
  }

  if ((s[0] & 0xF8) == 0xF0 && s[1] && s[2] && s[3] && (s[1] & 0xC0) == 0x80 &&
      (s[2] & 0xC0) == 0x80 && (s[3] & 0xC0) == 0x80) {
    cp = ((uint32_t)(s[0] & 0x07) << 18) | ((uint32_t)(s[1] & 0x3F) << 12) |
         ((uint32_t)(s[2] & 0x3F) << 6) | (uint32_t)(s[3] & 0x3F);
    *text += 4;
    return cp >= 0x10000 && cp <= 0x10FFFF ? cp : '?';
  }

  *text += 1;
  return '?';
}
